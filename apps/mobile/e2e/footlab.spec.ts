import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { randomUUID } from 'node:crypto';
import { parse } from 'dotenv';
const env = parse(readFileSync(resolve('../../.env')));
test('login, dashboard, club CRUD, comparador y sesión contra API real', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/'); await expect(page).toHaveURL(/auth\/login/);
  await page.getByLabel('Correo electrónico').fill('demo@footlab.local');
  await page.getByLabel('Contraseña', { exact: true }).fill(env.SEED_PASSWORD!);
  await page.getByRole('button', { name: 'Entrar a FOOTLAB' }).click();
  await expect(page.getByRole('heading', { name: 'Una mirada al rendimiento.' })).toBeVisible();
  await expect(page.getByText('Espacio de demostración.', { exact: false })).toBeVisible();
  await expect(page.getByText('Mateo Silva', { exact: true })).toHaveCount(0);
  await page.screenshot({ path: `../../docs/screenshots/dashboard-${test.info().project.name}.png`, fullPage: true });
  await page.getByRole('link', { name: 'Mi Club', exact: true }).filter({ visible: true }).click();
  await expect(page.getByRole('link', { name: 'Mateo Silva', exact: false })).toBeVisible();
  const name = `E2E ${randomUUID().slice(0, 8)}`;
  await page.getByRole('button', { name: 'Jugador', exact: true }).click();
  await page.getByLabel('Nombre completo').fill(name); await page.getByRole('combobox', { name: 'Posición', exact: true }).selectOption('MF');
  await page.getByRole('button', { name: 'Guardar', exact: true }).click();
  await expect(page.getByRole('link', { name, exact: false })).toBeVisible();
  await page.getByRole('row').filter({ hasText: name }).getByRole('button', { name: 'Archivar jugador' }).click();
  await expect(page.getByRole('link', { name, exact: false })).toHaveCount(0);
  await page.getByRole('link', { name: 'Analizar', exact: true }).filter({ visible: true }).click();
  await expect(page.getByRole('button', { name: 'Comparar', exact: false })).toBeEnabled();
  await page.getByRole('button', { name: 'Comparar', exact: false }).click();
  await expect(page.getByRole('heading', { name: 'Frente a frente' })).toBeVisible();
  await expect(page.getByText('Asistencias', { exact: true })).toBeVisible();
  await page.screenshot({ path: `../../docs/screenshots/comparison-${test.info().project.name}.png`, fullPage: true });
  await page.reload(); await expect(page.getByRole('button', { name: 'Comparar', exact: false })).toBeVisible();
  await page.getByRole('link', { name: 'Perfil', exact: true }).filter({ visible: true }).click();
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click();
  await expect(page).toHaveURL(/auth\/login/); expect(errors).toEqual([]);
});
